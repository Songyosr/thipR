test_that("ICD filtering is lazy, quoted, normalized and preserves source rows", {
  con <- .new_connection(test_config())
  local_mocked_bindings(dbGetQuery = function(...) stop("Unexpected query"), .package = "DBI")
  src <- dplyr::tbl(con, dbplyr::sql("SELECT * FROM synthetic WHERE yr = 2023"), vars = c("id", "dx", "dx 2"))
  q <- thip_filter_icd(src, c(" f12.1 ", "E11"), c("dx", "dx 2"), "prefix")
  sql <- as.character(dbplyr::sql_render(q))
  expect_match(sql, "WHERE yr = 2023", fixed = TRUE)
  expect_match(sql, "startsWith(code, 'F121')", fixed = TRUE)
  expect_match(sql, "src.`dx 2`", fixed = TRUE)
  expect_identical(colnames(q), colnames(src))
  expect_false(grepl("GROUP BY|DISTINCT|LIMIT", sql))
  exact <- thip_filter_icd(src, "F12.1", "dx", "exact")
  expect_match(as.character(dbplyr::sql_render(exact)), "hasAny", fixed = TRUE)
  expect_error(thip_filter_icd(src, " ", "dx"), "blank")
  expect_error(thip_filter_icd(src, "F12", "missing"), "cols")
  expect_error(thip_filter_icd(data.frame(dx = "F12"), "F12", "dx"), "lazy")
  expect_error(icd_flag(src, list(flag = "F12"), "id", "dx"), "local data frame")
})

test_that("lazy ICD filtering rejects unsupported notation before building SQL", {
  con <- .new_connection(test_config())
  local_mocked_bindings(dbGetQuery = function(...) stop("Unexpected query"), .package = "DBI")
  src <- dplyr::tbl(con, dbplyr::sql("SELECT * FROM synthetic"), vars = c("id", "dx"))
  expect_error(thip_filter_icd(src, "Q20-Q26", "dx", "prefix"), "Unsupported ICD notation")
  expect_error(thip_filter_icd(src, c("E11", "E1%"), "dx"), "condition: E1%")
  q <- thip_filter_icd(src, paste0("Q", 20:26), "dx", "prefix")
  expect_match(as.character(dbplyr::sql_render(q)), "startsWith(code, 'Q26')", fixed = TRUE)
})
